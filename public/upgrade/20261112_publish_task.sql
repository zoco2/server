CREATE TABLE IF NOT EXISTS `la_publish_task` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `tenant_id` int unsigned NOT NULL,
  `user_id` int unsigned NOT NULL,
  `content` varchar(500) NOT NULL,
  `platforms` varchar(64) NOT NULL,
  `notice_type` varchar(24) NOT NULL DEFAULT 'official_account',
  `push_mode` varchar(16) NOT NULL,
  `schedule_type` varchar(16) DEFAULT NULL,
  `push_time` char(5) DEFAULT NULL,
  `weekday` tinyint unsigned DEFAULT NULL,
  `start_date` date DEFAULT NULL,
  `end_date` date DEFAULT NULL,
  `status` varchar(16) NOT NULL,
  `next_run_at` bigint unsigned DEFAULT NULL,
  `wake_token` char(32) NOT NULL DEFAULT '',
  `last_run_at` bigint unsigned DEFAULT NULL COMMENT '最近一次尝试的计划执行时间（Unix 秒）',
  `last_run_status` varchar(16) NOT NULL DEFAULT '',
  `last_error` varchar(255) NOT NULL DEFAULT '',
  `create_time` bigint unsigned NOT NULL,
  `update_time` bigint unsigned NOT NULL,
  PRIMARY KEY (`id`),
  KEY `idx_owner` (`tenant_id`, `user_id`, `id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='用户发布任务';
