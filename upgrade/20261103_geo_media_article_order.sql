-- GEO 营销模块：媒体资源、稿件、投稿单
-- 与扩展应用 aigc_geo 无关，这是租户后台自有模块（tenantapi + api 用户端共用）。
-- 数据都按 tenant_id 隔离；稿件、投稿单还带 user_id（PC 前台用户）。

CREATE TABLE IF NOT EXISTS `la_geo_media` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `tenant_id` int unsigned NOT NULL COMMENT '租户ID',
  `sourceid` varchar(64) NOT NULL DEFAULT '' COMMENT '海讯社资源ID',
  `resource_type` tinyint unsigned NOT NULL DEFAULT 1 COMMENT '资源类型1软文2自媒体3海外发稿4海外社媒5贴吧6论坛7问答8友链9文案10小红书11百科12短视频13微信14微博15母语',
  `name` varchar(200) NOT NULL DEFAULT '' COMMENT '媒体名称',
  `classify` varchar(120) NOT NULL DEFAULT '' COMMENT '媒体分类',
  `region` varchar(120) NOT NULL DEFAULT '' COMMENT '区域',
  `portalmedia` varchar(120) NOT NULL DEFAULT '' COMMENT '综合门户',
  `industrystr` varchar(200) NOT NULL DEFAULT '' COMMENT '特别行业',
  `searchcoll` varchar(200) NOT NULL DEFAULT '' COMMENT '搜索收录说明',
  `entrancelink` varchar(500) NOT NULL DEFAULT '' COMMENT '入口链接',
  `caseurl` varchar(500) NOT NULL DEFAULT '' COMMENT '案例地址',
  `remark` varchar(500) NOT NULL DEFAULT '' COMMENT '备注',
  `costprice` decimal(12,2) NOT NULL DEFAULT 0.00 COMMENT '海讯成本价，建单price必须与海讯最新价相等',
  `price_ratio` decimal(8,3) NOT NULL DEFAULT 0.000 COMMENT '售价加成倍率，0表示取租户默认，售价=成本×倍率实时计算不落库',
  `price_type_json` text NULL COMMENT '多价格类别[{type,label,price}]',
  `linktype` tinyint unsigned NOT NULL DEFAULT 0 COMMENT '链接类型2可带网址0不可带网址',
  `publishtime` tinyint unsigned NOT NULL DEFAULT 0 COMMENT '发稿速度1一小时2二小时12半天24当天48隔天49两天以上',
  `newsresource` tinyint unsigned NOT NULL DEFAULT 0 COMMENT '百度新闻源1是0否',
  `weekendpublish` tinyint unsigned NOT NULL DEFAULT 0 COMMENT '周末可发1是0否',
  `searchcollint` tinyint unsigned NOT NULL DEFAULT 0 COMMENT '包收录1是0否',
  `pcweight` tinyint unsigned NOT NULL DEFAULT 0 COMMENT '电脑权重',
  `wapweight` tinyint unsigned NOT NULL DEFAULT 0 COMMENT '移动权重',
  `entrlevel` tinyint unsigned NOT NULL DEFAULT 0 COMMENT '入口级别0无1首页2频道3上级',
  `recommend` tinyint unsigned NOT NULL DEFAULT 0 COMMENT '推荐1是0否',
  `flag` tinyint unsigned NOT NULL DEFAULT 1 COMMENT '海讯状态1上架0下架',
  `deleted` tinyint unsigned NOT NULL DEFAULT 1 COMMENT '海讯删除1正常0已删除',
  `local_hidden` tinyint unsigned NOT NULL DEFAULT 0 COMMENT '我方隐藏1隐藏',
  `sync_status` varchar(16) NOT NULL DEFAULT 'synced' COMMENT 'synced/stale/gone',
  `detail_json` text NULL COMMENT '海讯原始行',
  `last_sync_time` int unsigned NOT NULL DEFAULT 0,
  `create_time` int unsigned NOT NULL DEFAULT 0,
  `update_time` int unsigned NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_tenant_source` (`tenant_id`,`sourceid`),
  KEY `idx_tenant_type` (`tenant_id`,`resource_type`,`flag`,`deleted`,`local_hidden`),
  KEY `idx_tenant_name` (`tenant_id`,`name`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='GEO媒体资源（海讯社镜像）';

CREATE TABLE IF NOT EXISTS `la_geo_article` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `tenant_id` int unsigned NOT NULL COMMENT '租户ID',
  `user_id` int unsigned NOT NULL DEFAULT 0 COMMENT '创建用户ID，0表示后台创建',
  `title` varchar(255) NOT NULL DEFAULT '' COMMENT '稿件标题',
  `digest` varchar(500) NOT NULL DEFAULT '' COMMENT '摘要',
  `content` longtext NULL COMMENT '正文HTML',
  `source_question` varchar(2000) NOT NULL DEFAULT '' COMMENT 'GEO关键词/问题，预留',
  `source` varchar(20) NOT NULL DEFAULT 'manual' COMMENT 'manual/ai',
  `preview_token` varchar(64) NOT NULL DEFAULT '' COMMENT '预览免登录令牌',
  `preview_url` varchar(500) NOT NULL DEFAULT '' COMMENT '预览地址，投稿content使用',
  `status` varchar(20) NOT NULL DEFAULT 'draft' COMMENT 'draft/ready/submitted/published/rejected',
  `publish_count` int unsigned NOT NULL DEFAULT 0 COMMENT '成功投稿次数',
  `remark` varchar(500) NOT NULL DEFAULT '',
  `delete_time` int unsigned NULL DEFAULT NULL,
  `create_time` int unsigned NOT NULL DEFAULT 0,
  `update_time` int unsigned NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_preview_token` (`preview_token`),
  KEY `idx_tenant_user` (`tenant_id`,`user_id`,`delete_time`,`id`),
  KEY `idx_tenant_status` (`tenant_id`,`status`,`delete_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='GEO稿件';

CREATE TABLE IF NOT EXISTS `la_geo_order` (
  `id` int unsigned NOT NULL AUTO_INCREMENT,
  `tenant_id` int unsigned NOT NULL,
  `user_id` int unsigned NOT NULL DEFAULT 0,
  `order_no` varchar(40) NOT NULL DEFAULT '' COMMENT '我方订单号=海讯ordernum',
  `article_id` int unsigned NOT NULL DEFAULT 0,
  `media_id` int unsigned NOT NULL DEFAULT 0,
  `sourceid` varchar(64) NOT NULL DEFAULT '',
  `resource_type` tinyint unsigned NOT NULL DEFAULT 1,
  `media_name` varchar(200) NOT NULL DEFAULT '',
  `price_type` tinyint unsigned NOT NULL DEFAULT 1 COMMENT '价格类别，微信/微博/短视频有多类别',
  `cost_price` decimal(12,2) NOT NULL DEFAULT 0.00 COMMENT '下单时海讯价',
  `sale_price` decimal(12,2) NOT NULL DEFAULT 0.00 COMMENT '用户实付（本期仅记账）',
  `title` varchar(255) NOT NULL DEFAULT '' COMMENT '下单标题快照',
  `content_url` varchar(500) NOT NULL DEFAULT '' COMMENT '下单内容预览地址',
  `remark` varchar(500) NOT NULL DEFAULT '',
  `origin` varchar(255) NOT NULL DEFAULT '',
  `status` tinyint NOT NULL DEFAULT -1 COMMENT '本地-1未推送；海讯0待安排1已安排2拒稿3发布成功待确认4反馈处理中5已完成100订单不存在',
  `remote_flag` tinyint NOT NULL DEFAULT -1 COMMENT '海讯原始flag',
  `publish_url` varchar(500) NOT NULL DEFAULT '',
  `fail_reason` varchar(500) NOT NULL DEFAULT '',
  `retryable` tinyint unsigned NOT NULL DEFAULT 0 COMMENT '1失败可重新推送',
  `push_attempts` tinyint unsigned NOT NULL DEFAULT 0,
  `last_push_time` int unsigned NOT NULL DEFAULT 0,
  `last_query_time` int unsigned NOT NULL DEFAULT 0,
  `finish_time` int unsigned NOT NULL DEFAULT 0,
  `power_log_id` int unsigned NOT NULL DEFAULT 0 COMMENT '预留：算力扣费流水',
  `create_time` int unsigned NOT NULL DEFAULT 0,
  `update_time` int unsigned NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  UNIQUE KEY `uk_order_no` (`order_no`),
  KEY `idx_tenant_status` (`tenant_id`,`status`),
  KEY `idx_tenant_user` (`tenant_id`,`user_id`,`id`),
  KEY `idx_tenant_article` (`tenant_id`,`article_id`),
  KEY `idx_query` (`status`,`last_query_time`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='GEO投稿单';

CREATE TABLE IF NOT EXISTS `la_geo_order_log` (
  `id` bigint unsigned NOT NULL AUTO_INCREMENT,
  `tenant_id` int unsigned NOT NULL DEFAULT 0,
  `order_id` int unsigned NOT NULL DEFAULT 0,
  `order_no` varchar(40) NOT NULL DEFAULT '',
  `from_status` tinyint NOT NULL DEFAULT -1,
  `to_status` tinyint NOT NULL DEFAULT -1,
  `action` varchar(20) NOT NULL DEFAULT '' COMMENT 'push/query/confirm/feedback/auto',
  `message` varchar(1000) NOT NULL DEFAULT '',
  `create_time` int unsigned NOT NULL DEFAULT 0,
  PRIMARY KEY (`id`),
  KEY `idx_order` (`order_id`,`id`)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COMMENT='GEO投稿单状态日志';